/** Embed texts, using Redis to skip anything we have already embedded (embeddings are deterministic). */
export async function embed(texts: string[]): Promise<number[][]> {
  if (!client) throw new Error('AI is not configured')
  const clean = texts.map((t) => t.replace(/\s+/g, ' ').trim().slice(0, 2000) || ' ')
  const keys = clean.map((t) => `ai:emb:${hash(t)}`)
  const { redis } = await import('./clients')
  const hits = await redis.mget<(number[] | null)[]>(...keys).catch(() => keys.map(() => null))
  const result: number[][] = hits.map((h) => (Array.isArray(h) ? h : []))
  const missing = result.map((r, i) => (r.length ? -1 : i)).filter((i) => i >= 0)
  if (missing.length) {
    const res = await client.embeddings.create({ model: EMBED_MODEL, input: missing.map((i) => clean[i]) })
    await Promise.all(res.data.map(async (d, n) => {
      result[missing[n]] = d.embedding
      await redis.set(keys[missing[n]], d.embedding as never, { ex: 7 * 86_400 }).catch(() => {})
    }))
  }
  return result
}

export const cosine = (a: number[], b: number[]) => {
  let dot = 0, na = 0, nb = 0
  for (let i = 0; i < a.length; i++) { dot += a[i] * b[i]; na += a[i] * a[i]; nb += b[i] * b[i] }
  return dot / (Math.sqrt(na) * Math.sqrt(nb) || 1)
}
